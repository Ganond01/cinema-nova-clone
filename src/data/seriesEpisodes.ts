/**
 * Parses duration string (e.g. '1 сезон • 16 серій' or '4 сезони') into season and episode counts
 */
function parseDurationToSeasons(duration?: string): Record<number, number> {
  const d = (duration || '').toLowerCase();
  const seasonMatch = d.match(/(\d+)\s*(?:сезон|сезони|сезонів|частини|частин)/i);
  const episodeMatch = d.match(/(\d+)\s*(?:серія|серії|серій)/i);

  const totalSeasons = seasonMatch ? Math.max(1, parseInt(seasonMatch[1], 10)) : 1;
  const totalEpisodes = episodeMatch ? parseInt(episodeMatch[1], 10) : (totalSeasons * 12);

  const seasonsMap: Record<number, number> = {};
  if (totalSeasons === 1) {
    seasonsMap[1] = Math.max(1, totalEpisodes);
  } else {
    const perSeason = Math.floor(totalEpisodes / totalSeasons);
    let rem = totalEpisodes % totalSeasons;
    for (let s = 1; s <= totalSeasons; s++) {
      seasonsMap[s] = Math.max(1, perSeason + (rem > 0 ? 1 : 0));
      if (rem > 0) rem--;
    }
  }
  return seasonsMap;
}

